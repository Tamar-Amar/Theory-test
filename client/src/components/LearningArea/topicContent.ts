/** בוחר קטגוריית מבחן מהמאגר לפי רשימת העדיפויות של הנושא */
export function resolveQuizCategory(
  meta: Meta | null,
  quizCategories: string[]
): string {
  const available = new Set(meta?.categories ?? []);
  return quizCategories.find((c) => available.has(c)) ?? "";
}
